fn data() -> Vec<Vec<f64>> {
    DATA.iter().map(|r| r.to_vec()).collect()
}

fn assert_close(found: f64, expected: f64, tol: f64, what: &str) {
    assert!((found - expected).abs() <= tol * (1.0 + expected.abs()), "{what}: {found} vs {expected}");
}

#[test]
fn em_matches_the_reference() {
    let fit = em_normal(&data(), &EmOptions { max_iterations: 100_000, tolerance: 1e-14 }).unwrap();
    assert!(fit.converged);
    for j in 0..4 {
        assert_close(fit.mean[j], EM_MEAN[0][j], 1e-10, "mean");
        for k in 0..4 {
            assert_close(fit.covariance[j][k], EM_COV[j][k], 1e-9, "covariance");
        }
    }
    for (i, row) in EM_FILLED.iter().enumerate() {
        for (j, &v) in row.iter().enumerate() {
            assert_close(fit.completed[i][j], v, 1e-9, "imputed value");
        }
    }
}

#[test]
fn low_rank_svd_matches_the_reference() {
    let options =
        SvdOptions { rank: 2, regularize: false, tolerance: 1e-28, max_iterations: 200_000, ..SvdOptions::default() };
    let fit = svd_impute(&data(), &options).unwrap();
    for (i, row) in SVD2_FILLED.iter().enumerate() {
        for (j, &v) in row.iter().enumerate() {
            assert_close(fit.completed[i][j], v, 1e-8, "imputed value");
        }
    }
}

#[test]
fn regularized_low_rank_svd_matches_the_reference() {
    let options = SvdOptions { rank: 2, tolerance: 1e-28, max_iterations: 200_000, ..SvdOptions::default() };
    let fit = svd_impute(&data(), &options).unwrap();
    assert!(fit.noise_variance.is_some_and(|s| s > 0.0));
    for (i, row) in SVD2_REG_FILLED.iter().enumerate() {
        for (j, &v) in row.iter().enumerate() {
            assert_close(fit.completed[i][j], v, 1e-8, "imputed value");
        }
    }
}

#[test]
fn regularization_settles_a_table_the_plain_iteration_drifts_on() {
    let wild: Vec<Vec<f64>> = WILD.iter().map(|r| r.to_vec()).collect();
    // Without shrinkage the rank-2 iteration does not settle (as in NumPy).
    let plain = SvdOptions { rank: 2, regularize: false, tolerance: 1e-8, ..SvdOptions::default() };
    assert!(!svd_impute(&wild, &plain).unwrap().converged);
    // With the default regularization it converges, to the reference values.
    let fit =
        svd_impute(&wild, &SvdOptions { rank: 2, tolerance: 1e-28, max_iterations: 200_000, ..SvdOptions::default() })
            .unwrap();
    assert!(fit.converged);
    for (i, row) in WILD_REG_FILLED.iter().enumerate() {
        for (j, &v) in row.iter().enumerate() {
            assert_close(fit.completed[i][j], v, 1e-8, "imputed value");
        }
    }
    let default = svd_impute(&wild, &SvdOptions::default()).unwrap();
    assert!(default.converged, "{} iterations", default.iterations);
}
