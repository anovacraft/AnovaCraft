"""Tabulate the orthogonal wavelet scaling filters used by stat-signal.

The coefficients are the standard published values (Daubechies 1992,
*Ten Lectures on Wavelets*, SIAM: Table 6.1 for the extremal-phase family,
§8.1 for the least-asymmetric "symlets", §8.2 for coiflets). This script
prints them to 17 significant digits from PyWavelets (MIT licence), the
reference implementation the transforms are checked against; the Rust tests
check orthonormality and vanishing moments independently.

    python3 -I crates/stat-signal/tests/data/wavelet_filters.py > crates/stat-signal/src/wavelet/filters.rs
"""
import pywt

names = ["haar"] + [f"db{i}" for i in range(1, 11)] + [f"sym{i}" for i in range(2, 11)] + [f"coif{i}" for i in range(1, 6)]
print("//! Scaling (low-pass reconstruction) filters of the orthogonal wavelets,")
print("//! generated by `tests/data/wavelet_filters.py`; see that script for sources.")
print()
print("/// `(name, reconstruction low-pass filter)` for every supported wavelet.")
print("#[allow(clippy::approx_constant)]")
print("pub(super) const FILTERS: &[(&str, &[f64])] = &[")
for n in names:
    w = pywt.Wavelet(n)
    vals = ", ".join(repr(float(v)) for v in w.rec_lo)
    print(f'    ("{n}", &[{vals}]),')
print("];")
