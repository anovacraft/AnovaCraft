# Reference values for crates/stat-bayes/tests/bayes_factor_reference.rs.
# R 4.3 with BayesFactor 0.9.12 (Debian r-cran-bayesfactor).
suppressMessages(library(BayesFactor))
options(digits = 15)
x <- c(0.42, 1.31, -0.25, 0.88, 1.92, 0.63, -0.47, 1.18, 0.95, 0.21, 1.57, 0.74)
y <- c(-0.31, 0.52, 0.11, -0.84, 0.36, -0.15, 0.67, -0.52, 0.08, 0.29)
show <- function(label, bf) cat(label, extractBF(bf, logbf = TRUE)$bf, "\n")
show("one_sample_medium", ttestBF(x, rscale = "medium"))
show("one_sample_wide", ttestBF(x, rscale = "wide"))
show("one_sample_greater", ttestBF(x, rscale = "medium", nullInterval = c(0, Inf))[1])
show("one_sample_less", ttestBF(x, rscale = "medium", nullInterval = c(-Inf, 0))[1])
show("two_sample_medium", ttestBF(x, y, rscale = "medium"))
show("two_sample_r1", ttestBF(x, y, rscale = 1))
show("t_stat_null", ttestBF(c(-1, 0, 1, 0.1, -0.12, 0.05), rscale = "medium"))
# Large sample via the statistic.
cat("large_t", ttest.tstat(t = 2.2, n1 = 400, rscale = sqrt(2)/2)$bf, "\n")
cat("two_t", ttest.tstat(t = -1.3, n1 = 25, n2 = 31, rscale = sqrt(2)/2)$bf, "\n")
# Correlations.
u <- c(1.2, 2.3, 2.9, 4.1, 5.5, 5.9, 7.2, 8.1, 8.8, 10.4, 11.0, 12.3, 13.1, 14.2)
v <- c(2.0, 1.4, 3.8, 3.1, 4.9, 6.6, 5.2, 7.9, 7.1, 8.3, 10.9, 9.4, 12.2, 11.1)
cat("r_uv", cor(u, v), "\n")
show("cor_medium", correlationBF(u, v, rscale = "medium"))
show("cor_ultrawide", correlationBF(u, v, rscale = 1))
show("cor_greater", correlationBF(u, v, rscale = "medium", nullInterval = c(0, 1))[1])
w <- c(0.3, -1.2, 0.8, 0.1, -0.4, 1.1, -0.9, 0.5, -0.2, 0.7)
z <- c(-0.5, 0.4, 0.2, -1.0, 0.9, -0.1, 0.3, -0.6, 0.8, 0.0)
cat("r_wz", cor(w, z), "\n")
show("cor_null", correlationBF(w, z, rscale = "medium"))
# Contingency tables.
tab <- matrix(c(18, 7, 11, 9, 14, 21), nrow = 2, byrow = TRUE)
show("ct_joint", contingencyTableBF(tab, sampleType = "jointMulti"))
show("ct_rows", contingencyTableBF(tab, sampleType = "indepMulti", fixedMargin = "rows"))
show("ct_cols", contingencyTableBF(tab, sampleType = "indepMulti", fixedMargin = "cols"))
show("ct_poisson", contingencyTableBF(tab, sampleType = "poisson"))
show("ct_joint_a2", contingencyTableBF(tab, sampleType = "jointMulti", priorConcentration = 2))
show("ct_rows_a2", contingencyTableBF(tab, sampleType = "indepMulti", fixedMargin = "rows", priorConcentration = 2))
show("ct_poisson_a2", contingencyTableBF(tab, sampleType = "poisson", priorConcentration = 2))
t3 <- matrix(c(10, 4, 6, 3, 9, 8, 5, 7, 12), nrow = 3, byrow = TRUE)
show("ct3_joint", contingencyTableBF(t3, sampleType = "jointMulti"))
show("ct3_cols", contingencyTableBF(t3, sampleType = "indepMulti", fixedMargin = "cols"))
show("ct3_poisson", contingencyTableBF(t3, sampleType = "poisson"))
# Posterior of delta (one sample), by MCMC.
set.seed(1)
post <- posterior(ttestBF(x, rscale = "medium"), iterations = 200000)
cat("delta_mean", mean(post[, "delta"]), "\n")
cat("delta_sd", sd(post[, "delta"]), "\n")
cat("delta_q025", quantile(post[, "delta"], 0.025), "\n")
cat("delta_q975", quantile(post[, "delta"], 0.975), "\n")
