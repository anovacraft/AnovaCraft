//! The bundled English stop-word list.
//!
//! Stop words are frequent function words (articles, pronouns, auxiliary
//! verbs, prepositions, conjunctions and a few common adverbs) that carry
//! little topical meaning and would otherwise dominate term counts (Luhn
//! 1958; Manning, Raghavan & Schütze 2008, *Introduction to Information
//! Retrieval*, §2.2.2). The list was compiled for this project from those
//! word classes; it is lower case and includes contracted forms written
//! with a straight apostrophe. It includes negations ("not", "no", "nor"),
//! which topic and term counts can drop; sentiment scoring never removes
//! stop words, so its negation handling still sees them.

