fn set() -> &'static HashSet<&'static str> {
    static SET: OnceLock<HashSet<&'static str>> = OnceLock::new();
    SET.get_or_init(|| ENGLISH.iter().copied().collect())
}

/// Whether `word` (lower case, straight apostrophes) is an English stop word.
#[must_use]
pub fn is_stop_word(word: &str) -> bool {
    set().contains(word)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn list_is_sorted_lower_case_and_unique() {
        let mut sorted = ENGLISH.to_vec();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(sorted, ENGLISH);
        assert!(ENGLISH.iter().all(|w| w.chars().all(|c| c.is_lowercase() || c == '\'')));
        assert!(is_stop_word("the") && is_stop_word("don't"));
        assert!(!is_stop_word("coffee") && !is_stop_word("The"));
    }
}
